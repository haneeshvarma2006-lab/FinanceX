import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve, sep } from 'node:path';
import { del, get, put } from '@vercel/blob';
import { getEnv } from '@/lib/env';

/**
 * Where bill photos live.
 *
 * One small interface so the rest of the app never names a provider: Vercel
 * Blob in production (a private store — nothing in it has a public URL, and
 * every read goes through the app, which checks the photo is yours), a
 * folder on disk for development and the end-to-end tests. Moving to another
 * provider later means adding one more implementation here.
 */
export type BillStore = {
  put(key: string, bytes: Uint8Array, contentType: string): Promise<void>;
  /** Null when the photo is not there. */
  get(key: string): Promise<{ body: ReadableStream<Uint8Array>; contentType: string } | null>;
  delete(keys: readonly string[]): Promise<void>;
};

const vercelBlob = (token: string): BillStore => ({
  async put(key, bytes, contentType) {
    await put(key, Buffer.from(bytes), {
      access: 'private',
      contentType,
      token,
      // Keys are already unique; a suffix would make them unfindable.
      addRandomSuffix: false,
      allowOverwrite: false,
    });
  },
  async get(key) {
    const result = await get(key, { access: 'private', token });
    if (!result || result.statusCode !== 200 || !result.stream) return null;
    return { body: result.stream, contentType: result.blob.contentType ?? 'image/jpeg' };
  },
  async delete(keys) {
    if (keys.length > 0) await del([...keys], { token });
  },
});

const localDisk = (root: string): BillStore => {
  const base = resolve(root);
  // Keys are generated by the app, but never trust a path to stay inside.
  const pathFor = (key: string) => {
    const path = resolve(base, key);
    if (!path.startsWith(base + sep)) throw new Error('Bill key escapes the storage folder');
    return path;
  };
  return {
    async put(key, bytes) {
      const path = pathFor(key);
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, bytes, { flag: 'wx' });
    },
    async get(key) {
      try {
        const bytes = await readFile(pathFor(key));
        return { body: new Response(bytes).body!, contentType: 'image/jpeg' };
      } catch {
        return null;
      }
    },
    async delete(keys) {
      await Promise.all(keys.map((k) => rm(pathFor(k), { force: true })));
    },
  };
};

/** The configured store, or null when bill photos are not kept. */
export function billStore(): BillStore | null {
  const env = getEnv();
  const mode =
    env.BILL_STORAGE === 'auto'
      ? env.BLOB_READ_WRITE_TOKEN
        ? 'vercel-blob'
        : 'none'
      : env.BILL_STORAGE;
  if (mode === 'vercel-blob' && env.BLOB_READ_WRITE_TOKEN)
    return vercelBlob(env.BLOB_READ_WRITE_TOKEN);
  if (mode === 'local') return localDisk(resolve(env.BILL_STORAGE_DIR));
  return null;
}
